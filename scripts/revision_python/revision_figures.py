def load_camera():
    h = pd.read_csv(T / "revision_R_A3_hallmark_camera_fry.tsv", sep="\t")
    defs = pd.read_csv(T / "npj_figure1_hallmark_definitions.tsv", sep="\t")
    h = h.merge(defs[["hallmark_id", "hallmark", "category"]], left_on="set", right_on="hallmark_id", how="left")
    sign = np.where(h.camera_direction == "Up", 1.0, -1.0)
    h["signed_log10p"] = sign * (-np.log10(h.camera_p.clip(lower=1e-12)))
    h["fdr"] = h.camera_fdr
    orig = pd.read_csv(T / "npj_figure1_hallmark_enrichment.tsv", sep="\t")[["brain_region", "contrast", "hallmark_id", "enrichment_z", "p_value", "fdr"]]
    orig.columns = ["brain_region", "contrast", "hallmark_id", "perm_z", "perm_p", "perm_fdr"]
    h = h.merge(orig, on=["brain_region", "contrast", "hallmark_id"], how="left")
    return h


