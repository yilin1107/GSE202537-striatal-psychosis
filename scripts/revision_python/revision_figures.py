def draw_method_forest(ax):
    tests = pd.read_csv(OUT / "revision_A6_nnls_tests.tsv", sep="\t")
    alt = pd.read_csv(OUT / "revision_A6_alternative_deconvolution_tests.tsv", sep="\t")
    ol = pd.read_csv(OUT / "revision_A6_ol_lineage_tests.tsv", sep="\t")
    allt = pd.concat([tests, alt, ol], ignore_index=True)
    allt = allt[(allt.brain_region == "Putamen")]
    short = {"log_nnls": "log2-NNLS", "linear_nnls_rowscaled": "row-scaled linear NNLS", "cibersort_hpa": "CIBERSORT (nu-SVR)", "music_tran_nac": "MuSiC (Tran 2021 ref.)"}
    groups = [("Oligodendrocyte", "o", BRAIN_COLORS["Oligodendrocyte"]), ("OPC", "s", BRAIN_COLORS["OPC"]), ("OPC+Oligodendrocyte", "D", "#2E7D32")]
    y = 0.0; ticks, labels = [], []
    for cls, marker, color in groups:
        ax.text(-0.128, y - 0.75, "OPC + oligodendrocyte (lineage)" if cls == "OPC+Oligodendrocyte" else cls, ha="left", va="center", fontsize=5.4, fontweight="bold", color="#222222")
        for m in ["log_nnls", "linear_nnls_rowscaled", "cibersort_hpa", "music_tran_nac"]:
            r = allt[(allt.method == m) & (allt.brain_cell_class == cls)]
            ticks.append(y); labels.append(short[m])
            if len(r) == 0 or not np.isfinite(r.beta.values[0]):
                ax.text(0, y, "not resolvable", ha="center", va="center", fontsize=4.6, color="#777777"); y += 1; continue
            r = r.iloc[0]
            ax.plot([r.ci_low, r.ci_high], [y, y], color=color, linewidth=1.0, solid_capstyle="round")
            ax.plot(r.beta, y, marker=marker, color=color, markersize=3.6, markeredgecolor="white", markeredgewidth=0.3)
            ax.text(0.128, y, f"P={r.p:.3f}" if r.p >= 0.001 else "P<0.001", ha="left", va="center", fontsize=4.6, color="#333333")
            y += 1
        y += 0.8
    ax.axvline(0, color="#777777", linewidth=0.5, linestyle="--")
    ax.set_yticks(ticks); ax.set_yticklabels(labels, fontsize=4.8)
    ax.set_ylim(y - 0.6, -1.5); ax.set_xlim(-0.13, 0.19)
    ax.set_xlabel("SCZ - control, arcsine-scale beta (95% CI)", fontsize=5.5)
    ax.set_title("Putamen: reference and method dependence", fontsize=7.0, pad=3)
    ax.spines[["top", "right"]].set_visible(False); ax.tick_params(axis="x", labelsize=5.0, width=0.5, length=2); ax.tick_params(axis="y", width=0.5, length=2, pad=1.5)


