def draw_hallmark_circle(ax, enr: pd.DataFrame, region: str, contrast="SCZ_vs_Control", vmax=4.0, label_fontsize=2.35):
    ordered = (enr[["hallmark_id", "category"]].drop_duplicates()
               .assign(category=lambda f: pd.Categorical(f["category"], categories=CATEGORY_ORDER, ordered=True))
               .sort_values(["category", "hallmark_id"]).reset_index(drop=True))
    n = len(ordered); width = 2 * np.pi / n; theta = np.arange(n) * width
    norm = mpl.colors.Normalize(vmin=-vmax, vmax=vmax)
    lookup = enr.set_index(["brain_region", "contrast", "hallmark_id"])
    colors, marks = [], []
    for i, row in ordered.iterrows():
        rec = lookup.loc[(region, contrast, row["hallmark_id"])]
        colors.append(DIV_CMAP(norm(np.clip(float(rec["signed_log10p"]), -vmax, vmax))))
        if float(rec["fdr"]) < 0.10:
            marks.append(theta[i] + width / 2)
    ax.bar(theta + width / 2, 0.28, width=width * 0.96, bottom=0.70, color=colors, edgecolor="white", linewidth=0.24)
    if marks:
        ax.scatter(marks, [0.84] * len(marks), s=5.2, color="black", zorder=5)
    for i, row in ordered.iterrows():
        ax.bar(theta[i] + width / 2, 0.055, width=width * 0.98, bottom=1.025, color=CATEGORY_COLORS[str(row["category"])], edgecolor="white", linewidth=0.2)
        angle = theta[i] + width / 2; rot = np.degrees(angle); ha = "left"
        if 90 < rot < 270:
            rot += 180; ha = "right"
        ax.text(angle, 1.155, m33.short_hallmark_label(str(row["hallmark_id"])), rotation=rot, rotation_mode="anchor", ha=ha, va="center",
                fontsize=label_fontsize, color="#222222", clip_on=False)
    n_sig = int((enr[(enr.brain_region == region) & (enr.contrast == contrast)].fdr < 0.10).sum())
    ax.text(0.5, 0.54, region, ha="center", va="center", fontsize=7.5, fontweight="bold", transform=ax.transAxes)
    ax.text(0.5, 0.435, f"{n_sig} camera FDR<0.10\nHallmark sets", ha="center", va="center", fontsize=4.8, color="#333333", transform=ax.transAxes)
    ax.set_ylim(0, 1.25); ax.set_axis_off()


def draw_category_counts(ax, enr, region, show_ylabels, xmax):
    d = enr[(enr.brain_region == region) & (enr.contrast == "SCZ_vs_Control") & (enr.fdr < 0.10)]
    y = np.arange(len(CATEGORY_ORDER))
    for yi, cat in zip(y, CATEGORY_ORDER):
        sub = d[d.category == cat]
        up = int((sub.camera_direction == "Up").sum()); dn = int((sub.camera_direction == "Down").sum())
        ax.barh(yi, up, height=0.62, color=CATEGORY_COLORS[cat], edgecolor="white", linewidth=0.3)
        ax.barh(yi, -dn, height=0.62, color=CATEGORY_COLORS[cat], alpha=0.45, edgecolor="white", linewidth=0.3, hatch="////")
        if up: ax.text(up + 0.15, yi, f"{up}", ha="left", va="center", fontsize=4.8, color="#333333")
        if dn: ax.text(-dn - 0.15, yi, f"{dn}", ha="right", va="center", fontsize=4.8, color="#333333")
    ax.axvline(0, color="#777777", linewidth=0.5)
    ax.set_yticks(y); ax.set_yticklabels(CATEGORY_ORDER if show_ylabels else [""] * len(y), fontsize=4.8)
    ax.invert_yaxis(); ax.set_xlim(-xmax, xmax)
    ax.set_title(region, fontsize=6.8, pad=2)
    ax.grid(axis="x", color="#D9D9D9", linewidth=0.35, alpha=0.7)
    ax.spines[["top", "right"]].set_visible(False)
    ax.tick_params(axis="x", labelsize=4.8, width=0.5, length=2); ax.tick_params(axis="y", width=0.5, length=2, pad=1.5)


